import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { directory, files, verify, validateBoundary } from '../../../../scripts/service-l03-review.mjs';
import { hash } from '../../../../scripts/g1-download-review.mjs';

const read = path => readFileSync(path);
const json = path => JSON.parse(read(path));
const manifestPath = directory + '/manifest.json';
const manifest = json(manifestPath);
assert.equal(manifest.schema, 'quantos-service-l03-evidence-manifest/v1');
validateBoundary(manifest.boundary);
assert.deepEqual(manifest.files.map(f => f.path), files(directory).filter(p => p !== manifestPath));
for (const entry of manifest.files) assert.equal(hash(read(entry.path)), entry.sha256, entry.path);
const receipt = json(directory + '/receipt.json');
assert.equal(manifest.sourceCommit, receipt.sourceCommit);
const result = verify(receipt);
assert.equal(result.rustCases, 28);
assert.equal(result.nodeCases, 80);
const status = json(directory + '/confirmation-status.json');
assert.equal(status.status, 'PENDING');
assert.equal(status.approval, null);
assert.equal(status.actualUserReply, null);
assert.equal(status.formalAccepted, false);
assert.equal(status.request.nodeId, 'SERVICE:L03');
assert.equal(status.request.stage, 'DEVELOPMENT');
assert.equal(status.request.sourceCommit, receipt.sourceCommit);
assert.equal(status.request.inputsDigest, hash(JSON.stringify(receipt.inputs)));
assert.equal(status.documentSha256, hash(read(status.document)));
const draft = JSON.parse(read(status.document).toString().match(/```json\s*([\s\S]*?)\s*```/)[1]);
assert.equal(draft.status, 'PENDING');
assert.equal(draft.draftedBy, 'Codex');
assert.equal(draft.mode, 'AGENT_DRAFT_USER_CONFIRMATION');
assert.deepEqual(draft.request, status.request);
assert.deepEqual(draft.reviewDimensions, ['Product', 'Frontend', 'BFF', 'QA', 'Security', 'Risk']);
assert.deepEqual(draft.request.reviewDimensions, draft.reviewDimensions);
assert.match(read(directory + '/preflight-01/legacy-boundary.log').toString(), /test result: FAILED\. 0 passed; 3 failed/);
assert.match(read(directory + '/preflight-02/http-process.log').toString(), /test result: ok\. 3 passed; 0 failed/);
console.log(JSON.stringify({ ...result, evidenceFiles: manifest.files.length, confirmation: status.status }));
